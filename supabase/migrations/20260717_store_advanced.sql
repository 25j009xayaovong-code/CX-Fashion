create or replace function public.create_order(payload jsonb)
returns uuid language plpgsql security definer set search_path = public as $$
declare order_id uuid := gen_random_uuid(); item jsonb; current_stock integer; coupon_row public.coupons%rowtype; subtotal_value integer := (payload ->> 'subtotal')::integer; discount_value integer := 0; shipping_value integer := 60; total_value integer;
begin
  if auth.uid() is null then raise exception 'Please sign in before checkout'; end if;
  if payload ->> 'coupon' is not null then
    select * into coupon_row from public.coupons where code = upper(payload ->> 'coupon') and active = true for update;
    if not found or (coupon_row.expires_at is not null and coupon_row.expires_at < now()) or (coupon_row.usage_limit is not null and coupon_row.used_count >= coupon_row.usage_limit) or subtotal_value < coupon_row.minimum_order then
      raise exception 'คูปองไม่สามารถใช้งานได้';
    end if;
    if coupon_row.type = 'percent' then discount_value := round(subtotal_value * coupon_row.value / 100.0); end if;
    if coupon_row.type = 'shipping' then shipping_value := 0; end if;
  end if;
  if subtotal_value = 0 then shipping_value := 0; end if;
  total_value := greatest(0, subtotal_value - discount_value + shipping_value);
  for item in select * from jsonb_array_elements(payload -> 'items') loop
    if item ->> 'variantId' is not null then
      select stock into current_stock from public.product_variants where id = (item ->> 'variantId')::bigint for update;
    else
      select stock into current_stock from public.products where id = (item ->> 'id')::bigint for update;
    end if;
    if current_stock is null or current_stock < (item ->> 'qty')::integer then raise exception 'ไซซ์สินค้าที่เลือกมีไม่เพียงพอ'; end if;
  end loop;
  insert into public.orders (id, order_number, user_id, buyer, contact, address, payment, subtotal, discount_amount, shipping_fee, coupon, coupon_label, total)
  values (order_id, payload ->> 'orderId', auth.uid(), payload ->> 'buyer', payload ->> 'contact', payload ->> 'address', payload ->> 'payment', subtotal_value, discount_value, shipping_value, coupon_row.code, coupon_row.label, total_value);
  for item in select * from jsonb_array_elements(payload -> 'items') loop
    if item ->> 'variantId' is not null then update public.product_variants set stock = stock - (item ->> 'qty')::integer where id = (item ->> 'variantId')::bigint; end if;
    update public.products set stock = greatest(0, stock - (item ->> 'qty')::integer) where id = (item ->> 'id')::bigint;
    insert into public.order_items (order_id, product_id, variant_id, name, price, quantity, size, image_url)
    values (order_id, (item ->> 'id')::bigint, nullif(item ->> 'variantId', '')::bigint, item ->> 'name', (item ->> 'price')::integer, (item ->> 'qty')::integer, item ->> 'size', item ->> 'img');
  end loop;
  if coupon_row.code is not null then update public.coupons set used_count = used_count + 1 where code = coupon_row.code; end if;
  return order_id;
end;
$$;
