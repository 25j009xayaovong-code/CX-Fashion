create table if not exists public.product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  size text not null,
  stock integer not null default 0 check (stock >= 0),
  unique (product_id, size)
);

alter table public.orders add column if not exists status text not null default 'pending' check (status in ('pending', 'paid', 'packing', 'shipped', 'completed', 'cancelled'));
alter table public.orders add column if not exists tracking_number text;
alter table public.order_items add column if not exists variant_id bigint references public.product_variants(id) on delete set null;

create table if not exists public.favorites (
  user_id uuid not null references public.profiles(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

create table if not exists public.coupons (
  code text primary key,
  label text not null,
  type text not null check (type in ('percent', 'shipping')),
  value integer not null default 0 check (value >= 0),
  minimum_order integer not null default 0 check (minimum_order >= 0),
  expires_at timestamptz,
  usage_limit integer,
  used_count integer not null default 0 check (used_count >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Convert existing sizes into stock records. The old total is distributed across its sizes.
insert into public.product_variants (product_id, size, stock)
select p.id, sized.size,
  floor(p.stock / greatest(cardinality(p.sizes), 1))::integer +
  case when sized.position <= p.stock % greatest(cardinality(p.sizes), 1) then 1 else 0 end
from public.products p
cross join lateral unnest(coalesce(nullif(p.sizes, '{}'), array['One size'])) with ordinality as sized(size, position)
on conflict (product_id, size) do nothing;

insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set public = true;

alter table public.product_variants enable row level security;
